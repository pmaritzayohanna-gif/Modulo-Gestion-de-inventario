    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
      try {
          if (txtID.getText().trim().isEmpty()||
             txtNombre.getText().trim().isEmpty()||
             txtPrecio.getText().trim().isEmpty()||
             txtStock.getText().trim().isEmpty()) {
            
            javax.swing.JOptionPane.showMessageDialog(this, "Completa todos los campos");
            return;
          }    
           
           Producto p = new Producto(
             Integer.parseInt(txtID.getText().trim()),
             txtNombre.getText().trim(),
             Double.parseDouble(txtPrecio.getText().trim()),
             Integer.parseInt(txtStock.getText().trim())
           );
           
           ProductoDAO dao = new ProductoDAO();
           dao.insertar(p);
           
           javax.swing.JOptionPane.showMessageDialog(this, "Producto guardado correctamente");
           
           txtID.setText("");
           txtNombre.setText("");
           txtPrecio.setText("");
           txtStock.setText("");
           
           cargarTabla();
           
           
      } catch (NumberFormatException e) {
          javax.swing.JOptionPane.showMessageDialog(this, "ID, precio y stock deben ser numericos");
      } catch (Exception e){
          javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
         
      }  
       
        
        
    }//GEN-LAST:event_btnGuardarActionPerformed

