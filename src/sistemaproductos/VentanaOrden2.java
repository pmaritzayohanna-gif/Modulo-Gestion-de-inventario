    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        try{
            if (txtID.getText().trim().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ingresa el ID a eliminar");
                return;
                
            }
            
            int id = Integer.parseInt(txtID.getText().trim());
            
            ProductoDAO dao = new ProductoDAO();
            dao.eliminar(id);
            
            javax.swing.JOptionPane.showMessageDialog(this, "Producto eliminado correctamente");
                
                txtID.setText("");
                txtNombre.setText("");
                txtPrecio.setText("");
                txtStock.setText("");
                
                cargarTabla();
                
                
            } catch (NumberFormatException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "El ID debe ser numerico");
                    
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
                
        }
    
           
            
              
            
    }//GEN-LAST:event_btnEliminarActionPerformed

